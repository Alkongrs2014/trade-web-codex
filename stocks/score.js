/* ---------------------------------------------------------------------
   الفريمات وأوزانها — الكبيرة أبطأ وأقل خداعاً فوزنها أعلى.
   نصيب كل فريم من النتيجة الكلية: 15د ‎10%‎، ساعة ‎20%‎،
   4 ساعات ‎30%‎، يومي ‎40%‎.
   --------------------------------------------------------------------- */
var TFS       = ["15m", "1h", "4h", "1d"];
var TF_LABEL  = { "15m": "15 دقيقة", "1h": "ساعة", "4h": "4 ساعات", "1d": "يومي" };
var TF_WEIGHT = { "15m": 0.5, "1h": 1, "4h": 1.5, "1d": 2 };

/* =====================================================================
   المنطقة الميتة — أهمّ ما في هذا الملف.

   النتيجة مجموعُ بواباتٍ نعم/لا، وكل بوابة تضيف وزنها كاملاً أو تطرحه
   كاملاً. فسهمٌ سعره يحوم **فوق** متوسّطه بسنتٍ واحد يأخذ ‎+1.0‎، وبعد
   دقيقةٍ صار تحته بسنت فيأخذ ‎−1.0‎ — انقلابُ ‎23.5‎ نقطة على فريمه من
   حركةٍ لا يراها أحد.

   قياسٌ فعلي قبل هذا التعديل (2026-09-13، 96 رمزاً مرصوداً):
     · ‎93 رمزاً من 96‎ فيه بوابةٌ واحدة على الأقل يفصلها عن الانقلاب
       أقلّ من ‎0.1%‎ من السعر.
     · أبل: `e20` لفريم 15د = 332.5657 والسعر 332.55 — الفرق **1.5 سنت**.
       إزاحةُ السعر سنتين تنقل نتيجة الفريم من 29.4 إلى 52.9.
     · ‎195 حالة مسجَّلة في `trend.json` تغيّرت فيها النتيجة والسعر لم
       يتغيّر بأيّ كسر، و‎146 حالة‎ قفزت ‎10+‎ نقاط بحركةٍ أقلّ من ‎0.15%‎.
     · بيتكوين انتقل من ‎−22.75‎ إلى ‎+11.37‎ بحركة ‎0.071%‎ — أي تغيّر
       تصنيفُه من «عرضي» إلى «ميل صاعد» بلا حركةٍ تُذكر.

   الحلّ: البوابة التي طرفاها متقاربان **لا تُصوّت لأيّ جهة** — تُضيف
   وزنها إلى المقام وصفراً إلى البسط. فيُدفع السهم الحائر نحو الصفر، وهو
   معنى «عرضي» بالضبط.

   والعتبة بـ ATR لا بنسبةٍ من السعر: ATR مقياس تقلّب الفريم نفسه، فتضيق
   المنطقة في السهم الهادئ وتتّسع في المتقلّب تلقائياً. نسبةٌ ثابتة كانت
   ستكون واسعةً على فريم 15د لسهمٍ هادئ وضيّقةً على اليومي لسهمٍ متقلّب.

   ‎0.15×ATR‎: على فريم 15د لأبل (ATR = 0.535) = **8 سنتات**، وعلى
   اليومي (ATR = 8.05) = **1.2 دولار**. أي أنها تحيّد الضجيج ولا تحيّد
   عبوراً حقيقياً — وهذا شرط القبول: عبورٌ أكبر من سُدس مدى الشمعة
   الواحدة ليس ضجيجاً.

   ومكسبٌ ثانٍ غير مقصود: قبل هذا كان `px > e200` يعيد `false` عند
   التساوي التامّ، فسلسلةٌ مجمَّدة (سعرٌ واحد لكل شمعاتها) تخرج بنتيجة
   ‎−50.59‎ — «ميل هابط» لأصلٍ لا يتحرّك إطلاقاً. صارت تخرج صفراً.
   ===================================================================== */
var DEAD_ATR = 0.15;

/* =====================================================================
   النتيجة الفنية من قيم المؤشرات عند نقطة واحدة: ‎−100‎ (هبوط قوي)
   إلى ‎+100‎ (صعود قوي).

   مستقلّة عن `analyze` عمداً: الأرشيف التاريخي يحتاج النتيجة عند كل
   شمعة من آلاف الشمعات، واستدعاء `analyze` على شريحة متنامية لكل شمعة
   تكلفته تربيعية. هنا تُحسب السلاسل مرة ثم تُستدعى هذه الدالة لكل نقطة.

   `atr` اختياريّ لكنه **مطلوب فعلياً**: بغيابه تكون المنطقة الميتة صفراً
   فتعود الدالة إلى سلوكها القديم الحادّ. كلّ مستهلكٍ في المشروع يمرّره.
   ===================================================================== */
function scoreFrom(o) {
  var px = o.px, atr = o.atr;
  var sc = 0, max = 0;
  /* العتبة من ATR الفريم نفسه. `Number.isFinite` لا `isFinite` العالمية:
     تلك تحوّل `null` إلى صفر فتقبله كرقمٍ صالح — مصيدة موثّقة. */
  var tol = (Number.isFinite(atr) && atr > 0) ? atr * DEAD_ATR : 0;

  /* بوابةُ مقارنة بين رقمين: صفرٌ داخل المنطقة الميتة، وإلا وزنُها
     بإشارة الفرق. الغائبُ لا يُضاف إلى المقام أصلاً — بوابةٌ لا نعرف
     جوابها ليست بوابةً محيَّدة، بل غير موجودة. */
  function cmp(a, b, w) {
    if (!Number.isFinite(a) || !Number.isFinite(b)) return;
    max += w;
    var d = a - b;
    sc += (Math.abs(d) <= tol) ? 0 : (d > 0 ? w : -w);
  }

  cmp(px, o.e200, 2.5);            // الاتجاه الأمّ
  cmp(o.e50, o.e200, 1.5);         // ترتيب المتوسّطات
  cmp(px, o.e20, 1.0);             // الزخم القصير

  if (Number.isFinite(o.hist)) {
    cmp(o.hist, 0, 1.5);           // إشارة MACD
    /* الميل: نفضّل مقارنة الهيستوغرام بقيمته السابقة كي تنالها المنطقة
       الميتة أيضاً — فرقٌ في الخانة الرابعة كان يقلب ‎11.8‎ نقطة. وحين
       لا تتوفّر القيمة السابقة (سجلاتٌ قديمة تحفظ الرايةَ وحدها) نرجع
       إلى الراية كما هي بدل إسقاط البوابة. */
    if (Number.isFinite(o.histPrev)) cmp(o.hist, o.histPrev, 0.5);
    else { max += 0.5; sc += o.histRising ? 0.5 : -0.5; }
  }

  /* RSI ثلاثيُّ الحالات أصلاً (‎>55‎ / ‎45–55‎ / ‎<45‎) فمنطقةُ حيادِه
     مبنيّةٌ فيه، ولا يُضاف إليه شيء. */
  if (Number.isFinite(o.rsi)) {
    max += 1;
    sc += o.rsi > 55 ? 1 : (o.rsi < 45 ? -1 : 0);
  }

  cmp(px, o.bbMid, 0.5);           // موضعه في نطاق بولنجر

  return max > 0 ? Math.max(-100, Math.min(100, sc / max * 100)) : 0;
}

/* النتيجة الكلية الموزونة عبر الفريمات */
function overallScore(byTf) {
  var sum = 0, wsum = 0;
  for (var i = 0; i < TFS.length; i++) {
    var a = byTf[TFS[i]];
    if (!a || !Number.isFinite(a.score)) continue;
    sum += a.score * TF_WEIGHT[TFS[i]];
    wsum += TF_WEIGHT[TFS[i]];
  }
  return wsum ? sum / wsum : null;
}

/* =====================================================================
   النطاقات — خمسة، وحدودها ‎±15‎ و‎±45‎.

   `bandOf` الحدُّ يخصّ النطاق الأعلى في الجهتين (‎−45‎ «ميل هابط» لا
   «هابط قوي»). كان `labelOf` القديم غير متناظر: يضمّ ‎+45‎ إلى الأعلى
   ويدفع ‎−45‎ إلى الأدنى — فكان `bandOf` في `track-signals` يخالفه عند
   الحدّ بالضبط. صار المصدرُ واحداً فانتهى الخلاف.
   ===================================================================== */
var BANDS = [-45, -15, 15, 45];
function bandOf(sc) {
  if (!Number.isFinite(sc)) return null;
  var n = 0;
  for (var i = 0; i < BANDS.length; i++) if (sc >= BANDS[i]) n++;
  return n;                                              // 0..4
}

/* =====================================================================
   هامش تثبيت النطاق (هيستريسس).

   المنطقة الميتة تُهدِئ الرقم، لكنها لا تمنع رقماً يستقرّ على الحدّ من
   عبوره ذهاباً وإياباً. والوسم أوقعُ من الرقم: من يرى «عرضي» ثم «ميل
   صاعد» ثم «عرضي» في نصف ساعة يقرأها إشاراتٍ متناقضة، لا رقماً يهتزّ.

   فلا يُغيَّر النطاق إلا بتجاوز حدّه بـ‎3‎ نقاط. والحلقتان لا شرطٌ واحد:
   النتيجة قد تقفز نطاقين في دورة، فالمشيُ خطوةً خطوة يضمن أن كل حدٍّ
   عُبر بهامشه — شرطٌ واحد كان سينقل من «عرضي» إلى «صاعد قوي» بمجرّد
   تجاوز ‎18‎.
   ===================================================================== */
var BAND_MARGIN = 3;
function bandStable(sc, prevBand) {
  var now = bandOf(sc);
  if (now === null) return null;
  if (!Number.isFinite(prevBand) || prevBand < 0 || prevBand > 4) return now;
  var b = prevBand;
  while (b < 4 && sc >= BANDS[b] + BAND_MARGIN) b++;
  while (b > 0 && sc <= BANDS[b - 1] - BAND_MARGIN) b--;
  return b;
}

var BAND_LABEL = [
  { t: "اتجاه هابط قوي", c: "var(--dn)",  k: "dn2" },
  { t: "ميل هابط",       c: "var(--dn)",  k: "dn1" },
  { t: "عرضي / غير واضح", c: "var(--neu)", k: "flat" },
  { t: "ميل صاعد",       c: "var(--up)",  k: "up1" },
  { t: "اتجاه صاعد قوي", c: "var(--up)",  k: "up2" }
];

/* `band` اختياري: مرّره حين يكون محفوظاً (الخادم يحسبه بالهيستريسس ويضعه
   في `summary.json`) كي يرى المستخدم الوسمَ المثبَّت لا وسمَ اللحظة. */
function labelOf(sc, band) {
  var b = Number.isFinite(band) ? band : bandOf(sc);
  if (b === null) return { t: "—", c: "var(--mut)", k: "na" };
  return BAND_LABEL[b];
}

