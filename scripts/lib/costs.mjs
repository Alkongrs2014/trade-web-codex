/* =====================================================================
   تكلفة التنفيذ — نموذجٌ صريح معلَن، لا أرقامٌ مدفونة.

   لماذا ملفٌ مستقل: الأرشيف والتتبّع الحيّ يجب أن يطبّقا **نفس** النموذج،
   وإلا صار السجلّ الحيّ يُقارَن بأرشيفٍ يقيس شيئاً آخر — وهي نفس علّة
   `plan.js` و`scans.js` ونفس حلّها.

   ولماذا التكلفة أصلاً: كل رقمٍ في الأرشيف كان يفترض تنفيذاً مثالياً عند
   السعر المعروض بلا عمولة. وهذا تفاؤلٌ **ثابت الاتجاه**: يرفع كل عائد
   ولا يخفض أيّاً منه، فيجعل الحافة تبدو موجبة وهي صفر. والصفقة القصيرة
   الأجل تدفع التكلفة نفسها التي تدفعها الطويلة، فالتكلفة تضرب استراتيجيات
   التداول السريع أشدّ ما تضرب — وهو تمييزٌ لا يظهر بلا نموذج.

   الانزلاق **كسرٌ من ATR لا نسبةٌ من السعر**: سهمٌ يتحرّك ‎4%‎ يومياً
   يُنفَّذ أسوأ من سهمٍ يتحرّك ‎0.5%‎ عند نفس السعر. والنسبة الثابتة تعامل
   الاثنين سواءً فتظلم الهادئ وتجامل المتقلّب.
   ===================================================================== */

/* القيم افتراضاتٌ معلنة تُعرض في الواجهة، لا حقائق. مرجعها: فرق العرض
   والطلب لسهمٍ أمريكي كبير يقارب ‎0.01–0.05‎ من ATR اليومي، والعمولة
   عند وسطاء التجزئة صفر أو كسرُ نقطة أساس. أخذنا الطرف المتشائم من
   كليهما: رقمٌ متفائل هنا يلوّث كل ما بُني فوقه. */
export const COSTS = {
  slipAtr: 0.05,      // كسرٌ من ATR لكل جهة (دخول وخروج)
  feeBps: 2,          // نقاط أساس لكل جهة — عمولة وضرائب تنفيذ
  lbl: "انزلاق ‎0.05×ATR‎ لكل جهة · عمولة ‎2‎ نقطة أساس لكل جهة"
};

/* سعر التنفيذ الفعلي: أسوأ من المطلوب دائماً، في الاتجاهين معاً.
   `side` هو ‎+1‎ للشراء و‎−1‎ للبيع — لا اتجاه الصفقة: إغلاق صفقة شراء
   بيعٌ، ويدفع انزلاقه نزولاً. */
export function fill(price, side, atr, c = COSTS) {
  if (!Number.isFinite(price) || !Number.isFinite(atr) || atr <= 0) return price;
  return price + side * atr * c.slipAtr;
}

/* =====================================================================
   العائد الصافي بالنسبة المئوية، موقَّعاً باتجاه الصفقة.

   الرسوم تُطرح **مرتين**: دخولاً وخروجاً. وطرحُها مرة واحدة خطأٌ شائع
   يجعل الصفقة تبدو أرخص مما هي بالنصف.
   ===================================================================== */
export function netReturn(entry, exit, dir, atr, c = COSTS) {
  if (!Number.isFinite(entry) || !Number.isFinite(exit) || entry <= 0) return null;
  // الدخول يدفع الانزلاق في جهة الصفقة، والخروج في عكسها
  const eIn  = fill(entry, dir, atr, c);
  const eOut = fill(exit, -dir, atr, c);
  if (!(eIn > 0)) return null;
  const gross = (eOut - eIn) * dir / eIn * 100;
  return gross - (c.feeBps / 100) * 2;
}

/* العائد الخام بلا تكلفة — يُحفظ بجانب الصافي لا بدلاً منه: الفرق بينهما
   هو حجم التكلفة، وهو معلومةٌ تُقرأ ولا تُستنتج. */
export function grossReturn(entry, exit, dir) {
  if (!Number.isFinite(entry) || !Number.isFinite(exit) || entry <= 0) return null;
  return (exit - entry) * dir / entry * 100;
}

export function selfCheckCosts(t, eq) {
  t("الانزلاق يسوء في الاتجاهين", () => {
    eq(fill(100, 1, 2) > 100, true, "الشراء أعلى");
    eq(fill(100, -1, 2) < 100, true, "البيع أدنى");
    eq(fill(100, 1, 0), 100, "بلا ATR لا انزلاق");
  });
  t("العائد الصافي أقلّ من الخام دائماً", () => {
    const g = grossReturn(100, 110, 1), n = netReturn(100, 110, 1, 2);
    eq(g > n, true, "الصافي أقلّ");
    const gs = grossReturn(100, 90, -1), ns = netReturn(100, 90, -1, 2);
    eq(gs > ns, true, "وكذلك في البيع");
  });
  t("صفقةٌ بلا حركة تخسر التكلفة لا تتعادل", () => {
    eq(netReturn(100, 100, 1, 2) < 0, true, "الدخول والخروج بنفس السعر خسارة");
  });
}

