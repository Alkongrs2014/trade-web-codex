/* =====================================================================
   تقريب الأسعار — بالأرقام المعنوية لا بالخانات العشرية.

   الأسعار عندنا تمتد من 0.0000051 (شيبا إينو) إلى 5,800 (بوكينج).
   والتقريب الثابت إلى أربع خانات عشرية يمحو الصغير منها **تماماً**:
   سعر شيبا صار صفراً، وشمعاتها كلها أصفاراً، وATR صفراً. ولم يظهر ذلك
   إلا حين رفضت بوابة النشر الصفَّ كاملاً — وهي تعمل لهذا بالضبط.

   ---------------------------------------------------------------------
   ولماذا ملفٌّ مستقلّ بعد أن كان مكرَّراً عمداً:

   كان نسختين في `fetch-market` و`fetch-quotes`، وعلّةُ التكرار المعلنة
   أن اختلافهما يجعل السعر يقفز بين الدورتين — أي أن **التباعد هو الخطر
   المعروف**، ثم تُرك بابُه مفتوحاً. فجاء مستهلكٌ ثالث ووقع فيه:
   `track-signals` كانت تكتب اللقطة بـ`r4` (خانات ثابتة)، فخرجت لقطة
   `SHIB-USD` بدخولٍ صفر ووقفٍ صفر وATR صفر وبلا هدفٍ واحد — **صفقةٌ
   محفوظة في السجلّ بمخاطرةٍ غير موجبة**، وهي أسوأ من غيابها لأنها
   تدخل الإحصاء برقمٍ لا معنى له.

   ولا يُستورد `rp` من `fetch-market`: استيرادُه يشغّل `main()` فيجلب
   الكون كلَّه (357 طلباً قِيست). فالمشترك يعيش هنا، كما `costs.mjs`
   مشتركٌ بين الأرشيف والتتبّع لنفس السبب بالضبط.

   وهذا ملفٌّ **نقيّ**: أرقام تدخل وأرقام تخرج، بلا شبكة ولا حالة.
   ===================================================================== */

/* السعر: أربع خانات لما فوق الواحد، وستّة أرقام معنوية لما دونه. */
export const rp = (v) => {
  if (v === null || v === undefined || !Number.isFinite(v)) return null;
  if (v === 0) return 0;
  return Math.abs(v) >= 1 ? Math.round(v * 10000) / 10000 : Number(v.toPrecision(6));
};

/* ما ليس سعراً — نسبةٌ أو مضاعفٌ أو نتيجة — مداه معروف فخاناته ثابتة.
   و`Number.isFinite` لا `isFinite` العالمية: الثانية تحوّل `null` صفراً
   فتقبله رقماً صالحاً، وهي مصيدةٌ موثّقة وقع فيها المشروع أكثر من مرة. */
export const r2 = (v) =>
  (v === null || v === undefined || !Number.isFinite(v)) ? null : Math.round(v * 100) / 100;

